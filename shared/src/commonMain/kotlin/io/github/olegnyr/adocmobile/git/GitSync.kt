package io.github.olegnyr.adocmobile.git

import kotlinx.coroutines.flow.Flow

/**
 * Интерфейс Git-синхронизации — общая половина третьего платформенного шва
 * (`FR-1`, `NFR-2`): модели платформенно-нейтральны, типы JGit границу не
 * пересекают, платформенная реализация подключается фабрикой при сборке экрана.
 *
 * Интерфейс, а не `expect`/`actual`, — по тому же прецеденту, что
 * `DocumentFileAccess` (журнал 004): логика экранов проверяется в `commonTest`
 * подделкой, а подделать `actual`-объявление нельзя. Платформа без реализации
 * отдаёт `null` вместо экземпляра — Git-разделы UI при этом не показываются
 * целиком (`FR-2`), iOS подключится независимо, когда появится libgit2-путь.
 *
 * В интерфейсе только то, что нужно закрытым слайсам: он растёт вместе с
 * этапами E1…E4, а не описывает всю фичу авансом.
 */
interface GitSync {

    /**
     * Клонировать репозиторий по [request]: холодный поток событий прогресса,
     * завершающийся ровно одним терминальным событием — [CloneEvent.Finished]
     * или [CloneEvent.Failed] (`TC-3`, `TC-4`).
     *
     * Отказ — событие, а не исключение: для экрана это штатный исход со своим
     * состоянием (`FR-7`), по прецеденту `DocumentOpenResult`. Повторная
     * подписка после отказа — новый запуск операции (`TC-4`).
     *
     * Долгую работу реализация обязана уводить с главного потока (`NFR-1`);
     * события доставляются в контекст собирающей корутины — модель экрана
     * собирает их в своей области на главном потоке.
     *
     * [auth] — способ авторизации (`FR-26`): токен предъявляется транспорту
     * и при успехе запоминается платформенным хранилищем секретов (`FR-28`),
     * чтобы fetch/pull/push переиспользовали его без повторного ввода.
     */
    fun clone(request: CloneRequest, auth: GitAuth = GitAuth.None): Flow<CloneEvent>

    /**
     * Репозиторий, уже живущий на устройстве, — `null`, если клона нет.
     *
     * Этим экран после перезапуска процесса попадает в состояние «репозиторий
     * есть», не клонируя заново (`FR-8`, `TC-6`). Сети вызов не касается —
     * читается только локальное состояние (`NFR-3`).
     */
    suspend fun openRepository(): RepositorySnapshot?

    /**
     * Файлы рабочей копии репозитория с [openRepository] — для списка экрана
     * репозитория (`FR-10` в части путей и времени). Служебный каталог `.git`
     * не перечисляется; порядок — по пути без учёта регистра. Пустой список —
     * клона нет или он пуст.
     */
    suspend fun listFiles(): List<RepoFile>

    /**
     * Состояние репозитория с [openRepository]: статусы файлов и счётчики
     * карточки ветки (`FR-9`, `FR-10`; `US-E5-02`). `null` — клона нет;
     * отказ чтения — *исключение*, а не `null`: «не прочитался» и «чистый»
     * обязаны различаться (находка ревью `SL-5`), отказ показывает экран.
     *
     * Сети вызов не касается (`NFR-3`, решение OQ-5 «fetch только вручную»):
     * [RepoStatus.behind] считается от последнего известного состояния origin
     * и между сетевыми операциями честно устаревает.
     */
    suspend fun status(): RepoStatus?

    /**
     * Сохранённое авторство коммитов; `null` — ещё не задано (`FR-22`).
     * Живёт в конфиге репозитория и переживает перезапуск процесса.
     */
    suspend fun author(): CommitAuthor?

    /**
     * Закоммитить *ровно перечисленные* файлы (`FR-17`, `TC-15`): пути — из
     * [RepoStatus.entries], снятый чекбоксом файл в коммит не попадает и
     * остаётся изменённым. [author] записывается в конфиг репозитория и
     * возвращается следующим [GitSync.author] (`FR-22`).
     *
     * Сети вызов не касается (`NFR-3`): commit — локальная операция,
     * отправка — отдельный шаг.
     */
    suspend fun commit(paths: List<String>, message: String, author: CommitAuthor): CommitResult

    /**
     * Забрать чужие правки из origin и влить в текущую ветку (`FR-13`,
     * `FR-14`, `FR-16`).
     *
     * Сетевой вызов по явному действию пользователя — fetch отдельной
     * кнопкой не существует (решение OQ-5). Отказ без сети не меняет
     * состояния репозитория (`FR-16`, `TC-14`); конфликт — не ошибка, а
     * исход [PullResult.Conflicted] со списком файлов для экрана слияния.
     */
    suspend fun pull(): PullResult

    /**
     * Текст конфликтного файла целиком; `null` — файла нет или путь не
     * прошёл рубежи доступа рабочей копии.
     *
     * Именно текст, а не разобранные участки: разбирает общий код
     * (`parseConflictFile`), и файл собирается обратно вместе с
     * неконфликтными строками. Прежний контракт «отдай участки» стирал
     * остальной файл при сборке — блокер ревью E3.
     */
    suspend fun conflictedText(path: String): String?

    /**
     * Записать разрешённый файл и отметить его разрешённым в индексе
     * (`FR-23`): текст собран общим кодом из выборов пользователя.
     */
    suspend fun resolveConflict(path: String, resolvedText: String): CommitResult

    /**
     * Завершить слияние merge-коммитом после разрешения всех участков
     * (`FR-24`, `TC-25`). Отказ — если неразрешённые участки остались.
     */
    suspend fun finishMerge(author: CommitAuthor): CommitResult

    /**
     * Отменить незавершённое слияние: репозиторий возвращается в состояние
     * до pull, локальные коммиты целы (`FR-25`, `TC-26`).
     *
     * Незакоммиченные правки *вне* слияния при этом сохраняются — из-за
     * решения `OQ-4` (запись открытого документа перед pull) они на диске
     * есть всегда, и `reset --hard` стирал бы работу пользователя (блокер
     * ревью E3).
     */
    suspend fun abortMerge(): CommitResult

    /**
     * Убрать stale-lock (`.git/index.lock`), оставшийся от убитого процесса,
     * и сообщить, был ли он (`NFR-5`, `TC-32`).
     *
     * Отдельный метод, а не молчаливая уборка внутри операций: снятие чужого
     * замка — действие с подтверждением пользователя, спека требует именно
     * подтверждения, а не автоматики.
     */
    suspend fun clearStaleLock(): Boolean

    /**
     * Отправить текущую ветку в origin (`FR-20`, `FR-21`).
     *
     * Единственный сетевой вызов после клона — по явному действию
     * пользователя (`NFR-3`, OQ-5/OQ-6: без сети — ошибка сразу, очереди
     * нет). Отказ никогда не трогает локальную историю: коммит остаётся на
     * месте (`FR-21`).
     */
    suspend fun push(): PushResult
}

/**
 * Авторство коммита — `user.name` и `user.email` (`FR-22`, решение OQ-8:
 * запрашивается при первом коммите и запоминается).
 */
data class CommitAuthor(
    val name: String,
    val email: String,
)

/** Чем закончился commit. */
sealed interface CommitResult {

    /** Коммит создан; счётчик `↑` карточки вырастет при следующем чтении статуса (`FR-11`). */
    data object Committed : CommitResult

    /** Коммит не создан; [error] уже содержит текст для пользователя. */
    data class Failed(val error: GitCommitError) : CommitResult
}

/** Чем закончился pull (`FR-14`: исход сообщается явно). */
sealed interface PullResult {

    /** Рабочая копия обновлена; [files] — что изменилось (для перечитки открытого файла). */
    data class Updated(val files: List<String>) : PullResult

    /** Расхождений не было — «уже актуально». */
    data object AlreadyUpToDate : PullResult

    /**
     * Слияние остановилось на конфликте; [paths] — файлы с разметкой
     * конфликта. Не ошибка: пользователь идёт на экран слияния (`UC-5`).
     */
    data class Conflicted(val paths: List<String>) : PullResult

    /** Pull не прошёл; состояние репозитория не тронуто (`FR-16`), [error] несёт текст. */
    data class Failed(val error: GitPullError) : PullResult
}

/** Почему pull не удался — классы отказов из `FR-16`. */
enum class GitPullError {
    /** Сети нет или remote недоступен. */
    Network,

    /** Remote потребовал авторизацию или отверг предъявленную. */
    AuthRequired,

    /** Локальные несохранённые изменения помешали слиянию. */
    DirtyWorkTree,

    /** Всё остальное: повреждённый ответ, отказ ввода-вывода, занятый индекс. */
    PullFailed,
    ;

    fun userMessage(): String = when (this) {
        Network ->
            "Забрать правки не удалось: нет сети или сервер недоступен. Репозиторий не изменился."

        AuthRequired ->
            "Сервер отверг доступ. Проверьте авторизацию — репозиторий не изменился."

        DirtyWorkTree ->
            "Слиянию мешают незакоммиченные правки. Закоммитьте их и повторите — репозиторий не изменился."

        PullFailed ->
            "Забрать правки не удалось. Попробуйте ещё раз — репозиторий не изменился."
    }
}

/**
 * Конфликтный участок файла (`FR-23`).
 *
 * Модель платформенно-нейтральна: разметку конфликта разбирает общий код
 * (`ConflictHunks.kt`), а не JGit, — так разбор и сборка результата
 * проверяются без устройства (`NFR-10`).
 *
 * @property ours строки локальной версии (`ЛОКАЛЬНО · HEAD`)
 * @property theirs строки удалённой версии (`ORIGIN/…`)
 * @property base строки общего предка — только в разметке `diff3`; в
 * результат не попадают никогда, но нужны, чтобы не утечь в [ours]
 * @property oursLabel метка стороны из разметки (`HEAD`, имя ветки);
 * `null` — метки не было. Это *не* автор и время: чтение коммитов сторон
 * (`FR-23`) — долг этапа UI, названный в журнале
 * @property theirsLabel то же для удалённой стороны
 */
data class ConflictHunk(
    val ours: List<SourceLine>,
    val theirs: List<SourceLine>,
    val base: List<SourceLine> = emptyList(),
    val oursLabel: String? = null,
    val theirsLabel: String? = null,
) {
    /** Строки стороны без терминаторов — для показа на экране. */
    fun oursText(): List<String> = ours.map { it.text }

    /** То же для удалённой стороны. */
    fun theirsText(): List<String> = theirs.map { it.text }
}

/** Чем закончился push. */
sealed interface PushResult {

    /** Ветка доехала до origin; `↑` обнулится при следующем чтении статуса (`FR-11`). */
    data object Pushed : PushResult

    /** Push не прошёл; локальный коммит цел (`FR-21`), [error] несёт текст. */
    data class Failed(val error: GitPushError) : PushResult
}

/** Почему push не удался — классы отказов из `FR-21`. */
enum class GitPushError {
    /** Сети нет или remote недоступен. */
    Network,

    /** Remote потребовал авторизацию или отверг предъявленную. */
    AuthRequired,

    /** Non-fast-forward: origin ушёл вперёд, сперва заберите чужие правки. */
    NonFastForward,

    /** Всё остальное: отказ хука, повреждённый ответ, внутренняя ошибка. */
    PushFailed,
    ;

    fun userMessage(): String = when (this) {
        Network ->
            "Отправить не удалось: нет сети или сервер недоступен. Коммит сохранён локально."

        AuthRequired ->
            "Сервер отверг доступ. Проверьте авторизацию — коммит сохранён локально."

        NonFastForward ->
            "В origin появились чужие коммиты. Заберите их (pull), затем отправьте снова — коммит сохранён локально."

        PushFailed ->
            "Отправить не удалось. Попробуйте ещё раз — коммит сохранён локально."
    }
}

/**
 * Почему commit не удался — по правилу `GitSyncError`: исход значением,
 * текст в общем коде.
 */
enum class GitCommitError {
    /** `index.lock` занят или остался от убитого процесса (`NFR-5`; протокол снятия — E3). */
    IndexLocked,

    /**
     * Слияние не идёт: отменять нечего (`FR-25`).
     * Отдельный исход, потому что «успех, ничего не сделав» уводил файл с
     * маркерами в историю следующим коммитом — блокер ревью E3.
     */
    MergeNotInProgress,

    /** Файл не читается как UTF-8: правка испортила бы его целиком (`NFR-6`). */
    NotUtf8,

    /**
     * В тексте остались строки с разметкой конфликта: коммитить такой файл
     * нельзя (регрессия ревью E3 — маркеры уезжали в историю).
     */
    MarkersLeft,

    /** Всё остальное: ошибка ввода-вывода, повреждённый индекс. */
    CommitFailed,
    ;

    fun userMessage(): String = when (this) {
        IndexLocked ->
            "Репозиторий занят другой операцией. Подождите её завершения и повторите."

        MergeNotInProgress ->
            "Слияние уже не идёт: отменять нечего. Обновите экран репозитория."

        MarkersLeft ->
            "В файле остались строки с разметкой конфликта — приложение не станет его коммитить. Разрешите конфликт вручную."

        NotUtf8 ->
            "Файл не в кодировке UTF-8 — приложение не станет его переписывать. Разрешите конфликт на компьютере."

        CommitFailed ->
            "Создать коммит не удалось. Попробуйте ещё раз."
    }
}

/**
 * Метка статуса файла — буквой, не только цветом (`NFR-9`, макет «01»).
 *
 * Три значения из `FR-10` плюс `D`, дозаявленный ревью `SL-5`: `git status`
 * выдаёт удаления, и файл, пропавший из копии, обязан быть виден в счётчике
 * изменений и индексе коммита, а не исчезать бесследно.
 * Конфликтный статус приходит с E3 (pull).
 */
enum class FileStatus {
    /** `M` — файл изменён относительно HEAD (в индексе или рабочей копии). */
    Modified,

    /** `A` — файл добавлен в индекс и в HEAD его ещё нет. */
    Added,

    /** `D` — файл удалён (в рабочей копии или индексе). Дозаявлен `SL-5`. */
    Deleted,

    /** `?` — файл не отслеживается. */
    Untracked,
}

/**
 * Строка статуса: файл и его изменение (`FR-10`).
 *
 * @property insertions добавленные строки (`+41`); `null` — счёт неприменим
 * (неотслеживаемый или бинарный файл)
 * @property deletions удалённые строки (`−6`); `null` — по той же причине
 */
data class StatusEntry(
    val path: String,
    val status: FileStatus,
    val insertions: Int? = null,
    val deletions: Int? = null,
)

/**
 * Состояние репозитория для карточки ветки и списка (`FR-9`, `FR-10`).
 *
 * @property ahead локальные коммиты, не отправленные в origin (`↑N`)
 * @property behind коммиты origin, не забранные локально (`↓N`) — от
 * последнего известного состояния origin (OQ-5), без сети
 * @property entries изменения рабочей копии и индекса; пустой список — чисто
 */
data class RepoStatus(
    val ahead: Int,
    val behind: Int,
    val entries: List<StatusEntry>,
) {
    /** Число локальных изменений для карточки и кнопки `COMMIT · N`. */
    val changeCount: Int get() = entries.size
}

/**
 * Файл рабочей копии, как его видит список экрана репозитория (`FR-10`).
 *
 * @property path путь от корня рабочей копии, разделитель — `/`
 * @property lastModifiedEpochMs время последней правки в миллисекундах эпохи
 * Unix — единица та же, что в `DocumentState.savedAt`
 */
data class RepoFile(
    val path: String,
    val lastModifiedEpochMs: Long,
)

/**
 * Запрос клонирования — поля формы макета «05» (`FR-3`, `FR-4`).
 *
 * Способа авторизации в запросе нет намеренно: E1 ограничен анонимным HTTPS,
 * а схема секретов — развилки `OQ-2`/`OQ-3`, не решаемые умолчанием в модели.
 * Поле появится вместе с этапом E2, когда владелец решит развилки.
 *
 * @property url адрес remote как ввёл пользователь
 * @property directoryName имя целевой папки клона внутри хранилища приложения
 * (само хранилище — решение `OQ-1`, модель о нём не знает)
 * @property branch ветка; `null` — ветка remote по умолчанию
 * @property shallow поверхностный клон `depth 1` — включён по умолчанию:
 * главная митигация памяти на мобильной куче (`FR-4`, разведка Q6)
 */
data class CloneRequest(
    val url: String,
    val directoryName: String,
    val branch: String? = null,
    val shallow: Boolean = true,
)

/** События клонирования: сколько угодно [Progress], затем ровно один терминал. */
sealed interface CloneEvent {

    /** Очередной срез прогресса для чертёжного блока (`FR-5`). */
    data class Progress(val progress: CloneProgress) : CloneEvent

    /** Клон готов и открыт; [repository] — данные для карточки ветки. */
    data class Finished(val repository: RepositorySnapshot) : CloneEvent

    /** Клонирование не удалось; частичного клона на диске не осталось (`FR-7`). */
    data class Failed(val error: GitSyncError) : CloneEvent
}

/**
 * Срез прогресса клонирования — процент, объекты, скорость (`FR-5`).
 *
 * @property phase человекочитаемое имя текущей фазы
 * @property completedObjects единиц работы сделано в текущей фазе
 * @property totalObjects всего единиц в фазе; `null` — транспорт объёма не сообщил
 * @property percent 0–100 *внутри фазы*; `null` — без [totalObjects] не
 * вычислить. Между фазами счёт начинается заново (как у нативного git):
 * глобальной монотонности у последовательности срезов нет
 * @property objectsPerSecond скорость фазы; `null` — время ещё не набежало.
 * Объекты в секунду, а не байты: байтов JGit наружу не отдаёт, а выдуманная
 * скорость хуже честной. Макет «05» единицу скорости не задаёт — вопрос
 * дизайну поднят отчётом слайса `SL-1`
 */
data class CloneProgress(
    val phase: String,
    val completedObjects: Int,
    val totalObjects: Int?,
    val percent: Int?,
    val objectsPerSecond: Int?,
)

/**
 * Склонированный репозиторий, как его видит карточка ветки (`FR-9`, минимум E1).
 *
 * @property directoryName имя папки клона в хранилище приложения
 * @property branch имя текущей ветки
 * @property remoteUrl адрес origin
 */
data class RepositorySnapshot(
    val directoryName: String,
    val branch: String,
    val remoteUrl: String,
)

/**
 * Почему клонирование не удалось — классы отказов из `FR-7`.
 *
 * Перечисление с готовым текстом, а не исключение, — по правилу
 * `DocumentAccessError` (фича 004): исход, названный значением, обязан быть
 * разобран, а текст сообщения — часть требования, общая для обеих платформ.
 */
enum class GitSyncError {
    /** Строка не похожа на адрес Git-репозитория или транспорт не поддержан. */
    InvalidUrl,

    /** Сети нет или remote недоступен. */
    Network,

    /** Remote потребовал авторизацию, которой в E1 нет (анонимный HTTPS). */
    AuthRequired,

    /** Целевая папка уже занята: там лежит прежний клон или посторонние файлы. */
    TargetExists,

    /** Имя целевой папки не годится: пустое, `..` или содержит разделители пути. */
    InvalidDirectory,

    /** В адресе учётные данные (`user:secret@`): секрет лёг бы в конфиг открытым текстом (`FR-30`). */
    CredentialsInUrl,

    /** Всё остальное: повреждённый ответ, нехватка места, внутренняя ошибка. */
    CloneFailed,
    ;

    /**
     * Сообщение пользователю — по правилу `DocumentAccessError.userMessage`:
     * текст живёт в общем коде, потому что «понятное сообщение» — требование
     * `FR-7`, а не оформление экрана.
     *
     * Адрес перед подстановкой чистится от встроенных учётных данных
     * ([sanitizedGitUrl]): сообщение уходит на экран и в любой журнал отказов,
     * а секретам там не место (`NFR-8`, `FR-30`).
     */
    fun userMessage(url: String): String = when (this) {
        InvalidUrl ->
            "Адрес «${sanitizedGitUrl(url)}» не похож на Git-репозиторий. Проверьте ссылку."

        Network ->
            "Не удалось связаться с «${sanitizedGitUrl(url)}»: нет сети или сервер недоступен."

        AuthRequired ->
            "Репозиторий «${sanitizedGitUrl(url)}» требует авторизацию — она появится в следующей итерации."

        TargetExists ->
            "Папка для «${sanitizedGitUrl(url)}» уже занята. Удалите прежний клон или выберите другое имя."

        InvalidDirectory ->
            "Имя папки не годится: нужно простое имя без разделителей пути."

        CredentialsInUrl ->
            "Уберите учётные данные из адреса «${sanitizedGitUrl(url)}»: секрет в URL ляжет в конфиг открытым текстом. Используйте поле ТОКЕН."

        CloneFailed ->
            "Клонировать «${sanitizedGitUrl(url)}» не удалось. Попробуйте ещё раз."
    }
}

/**
 * Адрес без встроенных учётных данных: `https://user:token@host/…` →
 * `https://host/…`.
 *
 * Общая функция для всего, что показывает или записывает адрес remote:
 * `NFR-8` запрещает URL с кредами в логах, а сообщение об ошибке — та же
 * поверхность утечки, только на экране. Чистка здесь, а не дисциплиной
 * вызывающих: одно место вместо каждого экрана и каждой платформы.
 */
fun sanitizedGitUrl(url: String): String = url.replace(CREDENTIALS_IN_URL_PATTERN, "$1")

/**
 * Есть ли в адресе учётные данные вида `user:secret@` (`FR-30`).
 *
 * Ловится именно пара с двоеточием: scp-форма SSH (`git@host:path`) — легальный
 * адрес без секрета, и отвергать её сообщением про токен значило бы врать.
 * Функция одна на форму и платформенный шов — рубежи зовут её независимо.
 */
fun hasCredentialsInUrl(url: String): Boolean = CREDENTIALS_PAIR_PATTERN.containsMatchIn(url)

// Жадный [^/\\s]* — до ПОСЛЕДНЕГО @ перед первым /: пароль с @ внутри
// (user:p@ss@host) иначе оставил бы хвост секрета в «чистом» адресе.
private val CREDENTIALS_IN_URL_PATTERN = Regex("(\\w+://)[^/\\s]*@")

// Пара user:secret@ в начале адреса или сразу после схемы; схема необязательна.
private val CREDENTIALS_PAIR_PATTERN = Regex("^(\\w+://)?[^/@\\s]+:[^/@\\s]*@")
