package io.github.olegnyr.adocmobile.render

/**
 * Контракт рендера — единственное, что общий код знает о превращении AsciiDoc в
 * HTML.
 *
 * `FR-1`: на входе строка, на выходе строка. Ни движок, ни платформа, ни формат
 * бандла в сигнатуру не попадают. За этот контракт позже цепляются Kroki
 * (поток 8), диагностика (поток 9) и экспорт (поток 10) — ломать его ради
 * удобства одной из них нельзя.
 *
 * Функция объявлена `suspend`, потому что работа заведомо длинная (142 мс на
 * предельном документе по замерам `T-013`) и заведомо не на главном потоке
 * (`FR-4`). Отменяемость даёт сама корутина, а не отдельный метод.
 *
 * Проблемы *документа* — незакрытый блок, неразрешённый `include`, ссылка в
 * никуда — отказом не считаются (`FR-8`): реализация возвращает HTML, а не
 * бросает исключение. Отказ движка (`FR-9`) — исключение; что при этом видит
 * пользователь, решает `SL-5`.
 */
interface AdocRenderer {

    /** AsciiDoc на входе, фрагмент HTML на выходе; диаграммы не рендерятся. */
    suspend fun render(source: String): String

    /**
     * То же, но с указанием, что делать с блоками диаграмм (`FR-3`, `FR-4`
     * фичи 008).
     *
     * Второй метод, а не параметр с умолчанием у первого: контракт `FR-1`
     * («строка на входе, строка на выходе») ломать ради одного потребителя
     * нельзя, а подделки рендерера в тестах пайплайна о диаграммах не знают и
     * знать не должны.
     *
     * Умолчание реализации — свести к [render] без диаграмм: подделке в тестах
     * пайплайна знать о диаграммах незачем.
     *
     * Плата за это умолчание названа прямо: реализация, забывшая переопределить
     * метод, молча вернёт документ без диаграмм, и поймать это сборкой нечем —
     * `TC-1` проверяет конкретный движок, а не обязанность реализаций. Пока
     * реализация одна, цена невелика; вторая (iOS) обязана переопределить оба
     * метода, и об этом сказано здесь, а не в чьей-то памяти.
     */
    suspend fun render(source: String, diagrams: DiagramOptions): String = render(source)
}

/**
 * Первый из двух платформенных швов фичи: где взять рендерер.
 *
 * Возвращается *один на процесс* экземпляр (`FR-3`): инициализация движка —
 * чтение ассета, создание рантайма, выполнение ~865 КБ скрипта — стоит 46–49 мс
 * по замерам `T-013`, и повторять её на каждый рендер незачем.
 *
 * Шов сделан функцией, а не `expect object`, ради интерфейса выше: пайплайн
 * дебаунсов (`SL-4`) проверяется в `commonTest` против поддельного рендерера, а
 * подделать `expect object` нечем.
 */
expect fun adocRenderer(): AdocRenderer
