package io.github.olegnyr.adocmobile.screen.app

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import io.github.olegnyr.adocmobile.document.DocumentSource
import io.github.olegnyr.adocmobile.document.DocumentTreeAccess
import io.github.olegnyr.adocmobile.document.TreeListResult
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.launch

/**
 * Что показывает корневой список (`FR-1`).
 *
 * Отдельный тип, а не набор флагов, — тем же приёмом, что `EditorDocument` и
 * `RepositoryScreenState`: состояния различаются действием пользователя, и
 * смешивать их нельзя.
 */
sealed interface RootListState {

    /** Источник ещё читается. */
    data object Loading : RootListState

    /**
     * Источника нет: первый запуск, право отдано или сохранённому источнику
     * нет реализации (`FR-2`, `FR-17`).
     *
     * Действия этого состояния состояние в себе не несёт: их состав зависит от
     * того, какие источники вообще собраны, и живёт в [ActiveSource]
     * ([ActiveSource.startActions]) — иначе один и тот же список пришлось бы
     * держать в двух местах.
     */
    data object NoSource : RootListState

    /**
     * Источник есть, но не читается: право отозвано, папка удалена (`FR-15`).
     * [message] — готовый текст шва (`TreeAccessError.userMessage`), экран его
     * не сочиняет.
     */
    data class Failed(val message: String) : RootListState

    /**
     * Файлы источника (`FR-14`).
     *
     * @property title имя источника для заголовка списка
     * @property files содержимое; пустой список — источник без документов, это
     * состояние, а не отказ (`FR-1a` фичи 004)
     */
    data class Listed(
        val title: String,
        val files: List<DocumentSource>,
    ) : RootListState
}

/**
 * Holder корневого списка — единственного списка файлов в приложении
 * (`FR-14`, `ADR-013`).
 *
 * Источник приходит интерфейсом [DocumentTreeAccess], а не конкретной
 * реализацией: у папки SAF и у рабочей копии клона он один и тот же, поэтому
 * список не знает, чьи файлы показывает, и знать не должен. Какой из двух
 * активен, решает [ActiveSource] (`FR-10`); Git-части списка — забота `SL-4`,
 * и до неё приложение остаётся полезным без Git.
 *
 * Несоставной класс с наблюдаемым состоянием — образец `EditorScreenModel` и
 * `RepositoryScreenModel`; события приходят с главного потока, класс не
 * потокобезопасен намеренно.
 *
 * @param scope область корутин экрана
 */
class RootListModel(
    private val sources: ActiveSource,
    private val scope: CoroutineScope,
) {

    /** Что показывать: наблюдаемое состояние для композиции. */
    var state: RootListState by mutableStateOf(RootListState.Loading)
        private set

    /**
     * Отказ открытия документа, с которым редактор вернул пользователя к
     * списку (`FR-9` фичи 005); `null` — показывать нечего.
     *
     * Отдельное поле, а не часть [RootListState.Listed], и это решение по
     * итогам ревью `SL-2`. Прежде уведомление жило внутри состояния и гасло
     * «следующим чтением» — а возврат на корень чтение порождает *всегда*,
     * поэтому текст исчезал раньше, чем пользователь успевал его прочесть.
     * Два правила гасили друг друга; переживает то, ради которого текст и
     * существует: причина отказа доходит до человека.
     *
     * Гаснет только явным действием — [noticeDismissed] или сменой источника
     * ([sourceChosen]): перечитка списка про отказ открытия ничего не знает.
     */
    var notice: String? by mutableStateOf(null)
        private set

    private var reading = false
    private var rereadRequested = false

    /**
     * Прочитать источник (`FR-7`).
     *
     * Не идемпотентен намеренно — тем же решением, что `RepositoryScreenModel.start`:
     * возврат из документа обязан увидеть папку такой, какой она стала, а не
     * такой, какой была на входе. Защита только от параллельного чтения:
     * второй запрос поверх идущего до шва не доходит.
     *
     * Отказ — состояние ([RootListState.Failed]), а не пустой экран: без
     * текста и действия пользователь остался бы перед вечной загрузкой.
     */
    fun start() {
        if (reading) {
            // Запрос поверх идущего чтения откладывается до его конца, а
            // не отбрасывается: источник мог смениться ровно в этот момент,
            // и оставить на экране прежний значило бы показать чужие файлы
            // (находка ревью `SL-2`).
            rereadRequested = true
            return
        }
        reading = true
        scope.launch {
            try {
                do {
                    rereadRequested = false
                    state = read()
                } while (rereadRequested)
            } finally {
                reading = false
            }
        }
    }

    /**
     * Активным стал другой источник — перечитать его.
     *
     * Поводов три и путь у них один: выбрана папка в системном диалоге, выбран
     * пункт переключения в меню (`FR-12`), право взято диалогом, пережившим
     * пересоздание активности.
     *
     * Отдельный вход, а не [start], потому что делает две вещи, которых у
     * перечитки нет: гасит [notice] (отказ открытия относился к документу
     * прежнего источника) и снимает с экрана содержимое прежнего источника до
     * прихода нового.
     */
    fun sourceChosen() {
        // Отказ относился к документу прежнего источника — на новый он не
        // переносится.
        notice = null
        // Содержимое прежнего источника снимается сразу, не дожидаясь конца
        // нового чтения: иначе в это окно шапка и файлы принадлежат одному
        // источнику, а меню уже считает активным другой (находка ревью
        // `SL-3`). Инвариант «на экране один источник» держится не только
        // внутри чтения, но и между ними.
        state = RootListState.Loading
        // Чтения отсюда нет намеренно: источник читает тот, кто показывает
        // список, и делает это ровно один раз. Смена метки — сигнал экрану
        // «перечитай», и он срабатывает одинаково, выбрали ли папку с корня
        // (экран в композиции, эффект перезапустится по новому ключу) или из
        // меню документа (экран смонтируется на возврате уже с новым ключом).
        // Прежде здесь стоял `start()`, и путь из документа давал два чтения
        // (находка ревью `SL-2`).
        sourceToken += 1
    }

    /**
     * Метка сменившегося источника — ключ эффекта, читающего список.
     *
     * Число, а не флаг: флаг пришлось бы гасить, и гасить его было бы некому,
     * пока экран не смонтирован.
     */
    var sourceToken: Int by mutableStateOf(0)
        private set

    /**
     * Редактор не смог открыть выбранный документ и вернул пользователя к
     * списку (`FR-9` фичи 005).
     *
     * Текст переживает перечитку списка и гаснет только явным действием
     * ([notice]): он про конкретную попытку, а не про источник, и терять его
     * из-за фонового чтения нельзя.
     *
     * Принимается в любом состоянии, включая [RootListState.Loading]:
     * восстановление после выгрузки процесса приходит на редактор, документ
     * может не открыться раньше, чем прочитается источник, и отбросить
     * причину в этот момент значило бы потерять её навсегда (находка ревью
     * `SL-2`). Показывать её или уступить более важному сообщению — решает
     * экран, а не модель.
     */
    fun documentOpenFailed(message: String) {
        notice = message
    }

    /** Пользователь закрыл плашку — причина прочитана. */
    fun noticeDismissed() {
        notice = null
    }

    /**
     * Одно чтение активного источника.
     *
     * Активного источника может не быть вовсе — первый запуск (`FR-2`) или
     * сборка без реализации Git с сохранённым выбором «клон» (`FR-17`); тогда
     * это пустое состояние, а не отказ: чинить нечего, надо выбрать.
     *
     * Дерево закрепляется *до* перечисления и берётся для заголовка оттуда же:
     * между обращениями есть приостановка, и три отдельных вопроса «какое
     * дерево сейчас» давали состояние из двух половин разных источников —
     * заголовок новой папки над файлами старой (находка ревью `SL-2`).
     * Сам источник проверяется тем же приёмом и по той же причине: с двумя
     * источниками (`FR-10`) сменить могли не только дерево внутри шва, но и
     * шов целиком.
     * Если сменилось что-то из двух, результат выбрасывается и чтение
     * повторяется: показывать несогласованное нельзя, а повторов столько же,
     * сколько смен источника, то есть считанные единицы.
     */
    private suspend fun read(): RootListState {
        while (true) {
            val access = sources.access ?: return RootListState.NoSource
            val tree = access.heldTree() ?: return RootListState.NoSource
            val result = access.listDocuments()
            if (sources.access !== access || access.heldTree()?.id != tree.id) continue

            return when (result) {
                is TreeListResult.Listed -> RootListState.Listed(
                    title = tree.displayName,
                    files = result.documents,
                )

                is TreeListResult.Failed ->
                    RootListState.Failed(result.error.userMessage(result.tree.displayName))
            }
        }
    }
}

/**
 * Источник документа по идентификатору из стека навигации (`FR-1`, `FR-6`).
 *
 * Порядок неслучаен: сначала [listed] — там лежит то, что пользователь только
 * что выбрал; затем [held] — им восстанавливается документ после выгрузки
 * процесса. `null` — опознать нечем, и хостингу остаётся вернуть корень:
 * пустой редактор без документа честнее не показывать.
 *
 * Функция, а не метод модели и не выражение внутри композиции: правило
 * выбора проверяется без экрана (`NFR-10`), как `filteredRepoFiles` и
 * `adocDocumentsOf`.
 *
 * @param listed текущее содержимое корневого списка; `null` — ещё не прочитан
 * @param held удержанный источник шва: последний открытый документ
 */
fun editorSourceFor(
    sourceId: String,
    listed: RootListState.Listed?,
    held: DocumentSource?,
): DocumentSource? =
    listed?.files?.firstOrNull { it.id == sourceId }
        ?: held?.takeIf { it.id == sourceId }

/**
 * Пора ли уводить пользователя с экрана документа на корень (`FR-6`).
 *
 * Документ не опознан — ещё не приговор: пока источник читается, список файлов
 * пуст просто потому, что его нет, и откат стёр бы восстановление, ради
 * которого стек и сохраняется. Уходить можно только когда чтение закончилось
 * и опознать всё равно нечем.
 *
 * Правило перехода, а не разводка композиции, поэтому функция, а не выражение
 * внутри `@Composable`: границы фичи прямо запрещают держать такое в
 * композиции, и проверяется оно без экрана (`NFR-10`).
 *
 * @param source результат [editorSourceFor]; `null` — опознать нечем
 * @param state состояние корневого списка на этот момент
 */
fun shouldLeaveEditorForRoot(source: DocumentSource?, state: RootListState): Boolean =
    source == null && state !is RootListState.Loading
