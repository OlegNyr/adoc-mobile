package io.github.olegnyr.adocmobile.git

/**
 * SSH-ключ приложения — публичная часть и её подписи (`FR-27`).
 *
 * Приватной части здесь нет и быть не может: она живёт только в хранилище
 * секретов (xref:../../adr/adr-015-ssh-key-storage.adoc[ADR-015]) и в память
 * поднимается лишь на время рукопожатия. Тип отдаётся экрану, попадает в
 * логи и снимки состояния — секрету в нём не место.
 *
 * @property publicKeyLine строка `ssh-ed25519 AAAA… комментарий` — её
 * пользователь копирует в настройки GitLab
 * @property fingerprint отпечаток `SHA256:…` для сверки с тем, что показывает
 * сервер
 * @property createdAtEpochMs когда ключ создан — подпись «добавлен …» на
 * экране; единица та же, что у `DocumentState.savedAt`
 */
data class SshKeyInfo(
    val publicKeyLine: String,
    val fingerprint: String,
    val createdAtEpochMs: Long,
)

/**
 * Что известно о ключе устройства (`TC-56`, слайс `SL-19`).
 *
 * Третье состояние заведено намеренно: «ключ на устройстве есть, но прочитать
 * его нельзя» — не то же самое, что «ключа нет». Выдать первое за второе
 * значило бы предложить создать ключ *без предупреждения о замене* и стереть
 * рабочую пару одним нажатием.
 */
sealed interface SshKeyPresence {

    /** Ключа нет: не создавался либо удалён. */
    data object None : SshKeyPresence

    /** Ключ есть и читается. */
    data class Present(val key: SshKeyInfo) : SshKeyPresence

    /**
     * Ключ на устройстве есть, но не читается: сброшен Keystore, повреждён
     * файл. Пересоздание возможно, но только через подтверждение — как
     * замена.
     */
    data object Unreadable : SshKeyPresence
}

/**
 * Генерация и хранение SSH-ключа устройства (`FR-27`, решение `OQ-3`).
 *
 * Платформенный шов: генерация опирается на криптопровайдер системы, а
 * хранение — на защищённое хранилище платформы. Общий код видит только
 * публичную часть.
 *
 * Реализация без Git-возможностей (iOS до libgit2) не создаётся вовсе —
 * тогда Git-разделы UI не показываются целиком (`FR-2`).
 */
interface SshKeyStore {

    /**
     * Состояние ключа устройства (`TC-56`).
     *
     * Показ ключа приватной части не поднимает: платформа читает открытую
     * половину, не расшифровывая секретную.
     */
    suspend fun currentKey(): SshKeyPresence

    /**
     * Ключ, целостность которого *проверена*; `null` — проверка не прошла.
     *
     * Нужен там, где строка уходит человеку в руки: он вставит её в настройки
     * сервера и тем самым выдаст доступ. Публичную половину показа никто не
     * заверяет (это цена дешёвого входа на экран), поэтому перед копированием
     * пара сверяется целиком — подменённая строка до буфера обмена не
     * доезжает (находка security-ревью `SL-20`).
     */
    suspend fun verifiedKey(): SshKeyInfo?

    /**
     * Создать ключ ed25519, заменив прежний.
     *
     * Замена — осознанное действие пользователя: старый ключ после этого
     * перестаёт подходить серверу, и экран обязан предупредить об этом до
     * вызова.
     *
     * @param comment комментарий ключа: имя устройства, чтобы владелец
     * узнал его в списке ключей сервера
     */
    suspend fun generateKey(comment: String): SshKeyInfo

    /** Забыть ключ: приватная часть удаляется вместе с публичной. */
    suspend fun deleteKey()
}
