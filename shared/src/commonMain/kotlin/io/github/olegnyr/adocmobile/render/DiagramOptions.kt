package io.github.olegnyr.adocmobile.render

/**
 * Адрес сервера Kroki по умолчанию — решение видения и `FR-24` фичи 008.
 *
 * Живёт рядом с контрактом рендера, а не в настройках: значение нужно и тогда,
 * когда настроек ещё нет — например, в тестах движка.
 */
const val DEFAULT_KROKI_SERVER_URL: String = "https://kroki.io"

/**
 * Что рендер должен сделать с блоками диаграмм — `FR-3` и `FR-4` фичи 008.
 *
 * Отдельный параметр конвертации, а не настройка внутри рендерера: движок —
 * синглтон на процесс (`FR-3` фичи 003), а режим диаграмм пользователь меняет
 * когда угодно. Состояние в синглтоне означало бы гонку между экраном настроек
 * и идущим рендером; параметр вызова её исключает.
 *
 * Выключенный режим — это *нерегистрация расширения*, а не пустой адрес: в
 * выводе не появляется ни одного адреса Kroki, и уходить наружу нечему
 * (`FR-27`, решение владельца `OQ-2`). Поэтому умолчание здесь — [Disabled]:
 * тот, кто не сказал про диаграммы ничего, не отправляет документ на чужой
 * сервер.
 *
 * @property krokiEnabled регистрировать ли расширение в этой конвертации.
 * @property serverUrl база адреса изображений; попадает в документ атрибутом
 * `kroki-server-url`. Проверка формата — обязанность настроек (`FR-25`), здесь
 * значение только переносится.
 */
data class DiagramOptions(
    val krokiEnabled: Boolean,
    val serverUrl: String = DEFAULT_KROKI_SERVER_URL,
) {
    init {
        require(serverUrl.none { it in UNSAFE_IN_SERVER_URL || it.code < 0x20 || it.code == 0x7F }) {
            "Адрес сервера Kroki содержит символ, недопустимый в адресе"
        }
    }

    companion object {

        /** Диаграммы не рендерятся; сеть не задействована ничем. */
        val Disabled: DiagramOptions = DiagramOptions(krokiEnabled = false)
    }
}

/**
 * Символы, которых в адресе сервера быть не может, — вторая граница (`TC-38`).
 *
 * Первую границу — подстановку в текст скрипта — закрывает `jsonStringLiteral`.
 * Но адрес живёт дальше: расширение склеивает из него адрес изображения, а
 * конвертер подставляет результат в `+<img src="…">+` *без* экранирования
 * (`alt` он экранирует, `src` — нет). Кавычка в адресе означала бы произвольную
 * разметку в странице превью, то есть нарушение `FR-13` («ничего, кроме блоков
 * диаграмм, не меняется»).
 *
 * Проверка формата адреса — обязанность настроек (`FR-25`, слайс `SL-6`), и
 * здесь она не дублируется: тут отсекается ровно то, что делает значение
 * опасным для разметки, а не то, что делает его неправильным адресом. Шов
 * рендера не имеет права полагаться на то, что кто-то выше уже проверил:
 * конструктор публичный, а экрана настроек ещё нет вовсе.
 */
private val UNSAFE_IN_SERVER_URL: Set<Char> = setOf('"', '\'', '<', '>', '`', ' ', '\\')
