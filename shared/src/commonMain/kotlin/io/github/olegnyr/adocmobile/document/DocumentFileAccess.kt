package io.github.olegnyr.adocmobile.document

/**
 * Почему документ не открылся.
 *
 * Перечисление, а не исключение: `FR-3` требует обрабатывать потерю доступа
 * *штатным сценарием*, а не сбоем. Исключение, дошедшее до интерфейса, — это
 * всегда либо падение, либо `catch (e: Exception)` где-то по дороге; исход,
 * названный значением, обязан быть разобран.
 */
enum class DocumentAccessError {
    /**
     * Постоянное разрешение больше не действует.
     *
     * Разведка предупреждала, что оно не гарантировано навсегда: система может
     * потерять право при очистке данных, пользователь — отозвать его руками.
     */
    PermissionLost,

    /** Файл исчез или переехал: пользователь удалил его, отключил накопитель, вышел из облачного хранилища. */
    NotFound,

    /** Файл не читается как UTF-8. Догадываться о кодировке мы не беремся — см. открытые вопросы спеки. */
    NotUtf8,

    /** Всё остальное: ошибка ввода-вывода, провайдер вернул отказ. */
    ReadFailed,
    ;

    /**
     * Сообщение пользователю.
     *
     * Живёт в общем коде, а не в экране, потому что это часть требования `FR-3`,
     * а не оформление: сообщение обязано быть понятным и проверяется тестом.
     * Второй платформе оно достанется тем же текстом.
     */
    fun userMessage(displayName: String): String = when (this) {
        PermissionLost ->
            "Доступ к файлу «$displayName» больше не действует. Выберите его заново."

        NotFound ->
            "Файл «$displayName» не найден: возможно, он удалён или перемещён."

        NotUtf8 ->
            "Файл «$displayName» не читается как UTF-8. Другие кодировки пока не поддерживаются."

        ReadFailed ->
            "Не удалось прочитать файл «$displayName». Попробуйте открыть его ещё раз."
    }
}

/**
 * Почему запись не удалась.
 *
 * Отдельное перечисление, а не переиспользование [DocumentAccessError]:
 * у чтения есть исход «не UTF-8», которого у записи не бывает, а у записи —
 * «нет места», которого не бывает у чтения. Классы отказов из `FR-17`:
 * нет прав, нет места, файл исчез — плюс общий отказ ввода-вывода.
 */
enum class DocumentWriteError {
    /** Права на запись нет: не выдано провайдером или отозвано. */
    PermissionLost,

    /** Файл исчез или переехал. */
    NotFound,

    /** На устройстве кончилось место. */
    NoSpace,

    /** Всё остальное: ошибка ввода-вывода, отказ провайдера. */
    WriteFailed,
    ;

    /**
     * Сообщение пользователю — по тому же правилу, что у
     * [DocumentAccessError.userMessage]: текст — часть требования `FR-17`
     * («отказ записи показывается пользователю»), а не оформление экрана.
     */
    fun userMessage(displayName: String): String = when (this) {
        PermissionLost ->
            "Нет права на запись в файл «$displayName». Выберите его заново."

        NotFound ->
            "Файл «$displayName» не найден: возможно, он удалён или перемещён."

        NoSpace ->
            "Не удалось сохранить «$displayName»: на устройстве закончилось место."

        WriteFailed ->
            "Не удалось сохранить файл «$displayName». Правки остаются в редакторе."
    }
}

/** Чем закончилась попытка записать документ. */
sealed interface DocumentWriteResult {

    /** Текст лежит в файле. */
    data object Written : DocumentWriteResult

    /** Запись не удалась; [error] уже содержит текст для пользователя. */
    data class Failed(val source: DocumentSource, val error: DocumentWriteError) : DocumentWriteResult
}

/** Чем закончилась попытка открыть документ. */
sealed interface DocumentOpenResult {

    /** Документ прочитан и готов к правке. */
    data class Opened(val document: DocumentState) : DocumentOpenResult

    /** Документ не открылся; [error] уже содержит текст для пользователя. */
    data class Failed(val source: DocumentSource, val error: DocumentAccessError) : DocumentOpenResult
}

/**
 * Байты файла — в модель документа.
 *
 * Общая половина файлового шва. Платформенная сторона умеет ровно одно —
 * достать байты по своей ссылке; всё, что можно решить без платформы
 * (кодировка, тип переводов строк, начальное состояние), решается здесь.
 * Так `NFR` «доля общего кода» выполняется не обещанием, а составом файлов.
 *
 * Строгий разбор UTF-8 намеренный: `decodeToString` по умолчанию заменяет
 * непонятые байты на `U+FFFD`, то есть тихо портит текст, и при следующей
 * записи подмена уходит в файл пользователя.
 */
fun openDocument(source: DocumentSource, bytes: ByteArray): DocumentOpenResult =
    try {
        DocumentOpenResult.Opened(
            DocumentState.opened(source, bytes.decodeToString(throwOnInvalidSequence = true)),
        )
    } catch (_: CharacterCodingException) {
        DocumentOpenResult.Failed(source, DocumentAccessError.NotUtf8)
    }

/**
 * Файловый шов: прочитать документ, записать его и удержать выданный доступ.
 *
 * Интерфейс, а не `expect`/`actual`, — расхождение с разделом «Технический
 * подход» спеки, сделанное сознательно. Причина: `SL-4` (автосохранение)
 * обязан проверяться в `commonTest` подставным доступом, а подставить
 * `actual`-объявление нельзя. Границы шва при этом те же, что в спеке:
 * чтение, запись и удержание разрешения, и ничего сверх.
 *
 * Запись добавлена слайсом `SL-6` после решения `FR-20` (запись напрямую,
 * атомарность не гарантируется — цена записана в спеке): до решения сигнатуру
 * не придумывали, чтобы не решить вопрос умолчанием.
 */
interface DocumentFileAccess {

    /**
     * Записать текст файла по ссылке источника.
     *
     * На вход приходит *текст файла*, а не текст редактора: переводы строк уже
     * восстановлены моделью ([DocumentState.fileText]) — шов только кодирует
     * UTF-8 и пишет байты. Иначе знание о типах переводов строк расползлось бы
     * на обе стороны шва.
     *
     * Запись идёт напрямую в файл пользователя, без временного файла и замены
     * (`FR-20`, решение владельца): обрыв может оставить файл записанным
     * наполовину, и это принятая цена — несохранённый текст остаётся в памяти
     * (`FR-17`), пользователь повторяет запись.
     *
     * `suspend` по той же причине, что у [open]: уходить с главного потока
     * обязана каждая платформа, а не та, что вспомнила.
     */
    suspend fun write(source: DocumentSource, fileText: String): DocumentWriteResult

    /**
     * Прочитать документ по ссылке источника.
     *
     * `suspend` в контракте, а не по усмотрению реализации: `FR-6` требует,
     * чтобы открытие файла не блокировало интерфейс, и уходить с главного
     * потока обязана каждая платформа.
     */
    suspend fun open(source: DocumentSource): DocumentOpenResult

    /**
     * Источник, доступ к которому удерживается постоянным разрешением.
     *
     * `null` — удерживать нечего. Ненулевой ответ *не* обещает, что файл
     * прочитается: право могло быть потеряно, а файл удалён, и узнать об этом
     * можно только попыткой ([open] вернёт [DocumentAccessError.PermissionLost]
     * или [DocumentAccessError.NotFound]).
     */
    fun heldSource(): DocumentSource?

    /** Перестать удерживать доступ: документ закрыт или доступ к нему потерян. */
    fun release()
}
