package io.github.olegnyr.adocmobile.diagram

/**
 * Загрузка изображения диаграммы — вторая и последняя платформенная
 * потребность фичи (`ADR-009`, `OQ-7`).
 *
 * Интерфейс, а не `expect`/`actual`, по той же причине, что [Inflate]: швов у
 * рендера и превью ровно два, а подделать интерфейс в тестах можно, `expect
 * object` — нет. Вся политика — что грузить, в каком порядке, что делать с
 * отказом — живёт в общем коде; здесь только «сходить по адресу и принести
 * байты».
 *
 * `null` — не вышло, и это штатный исход: сети нет, сервер ответил ошибкой,
 * истёк таймаут. Причина наружу не выдаётся намеренно: показываем мы во всех
 * случаях одно и то же (`ADR-011`), а разбор причин — соблазн начать их
 * показывать.
 *
 * Схему адреса реализация не проверяет: политика «только `https`» живёт в
 * настройках (`FR-25`, решение `OQ-3`), и дублировать её здесь значило бы иметь
 * два места, где её можно забыть поменять.
 */
fun interface DiagramTransport {

    /** Загружает изображение по адресу; `null` — не вышло. */
    suspend fun fetch(url: String): ByteArray?
}
