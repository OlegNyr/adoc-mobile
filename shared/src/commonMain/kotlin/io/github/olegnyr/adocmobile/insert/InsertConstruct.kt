package io.github.olegnyr.adocmobile.insert

/**
 * Конструкция панели быстрой вставки: что именно встаёт в текст по касанию
 * кнопки — слайсы `SL-1`/`SL-2` фичи 006-quick-insert-panel.
 *
 * Иерархия запечатана намеренно: применение конструкции ([insertEditFor])
 * разбирает её исчерпывающим `when`, и новая разновидность не скомпилируется,
 * пока не описано её поведение.
 *
 * Здесь только данные без поведения (`NFR-10`): сама вставка — чистая функция
 * в `InsertApplier.kt`, проверяемая в `commonTest` без устройства.
 */
sealed interface InsertConstruct

/**
 * Инлайн-конструкция с одинаковым маркером с обеих сторон: `*жирный*`,
 * `_курсив_`, `` `моноширинный` ``.
 *
 * Непустое выделение оборачивается маркерами буквально (`FR-7`); пустое —
 * вставляется пара маркеров, каретка между ними (`FR-8`).
 */
data class InlineWrap(val marker: String) : InsertConstruct

/**
 * Строчная конструкция: префикс логической строки каретки (`FR-10`) —
 * заголовки и маркер списка.
 *
 * Повтор — переключатель (решение `OQ-2`): префикс на строке, уже
 * начинающейся с него, снимается. Строка с *другим* префиксом — не повтор:
 * конструкция вставляется буквально, чинить разметку — не дело панели.
 *
 * @property prefix префикс вместе с разделяющим пробелом: `"== "`, `"* "`
 * @property eachSelectedLine многострочное выделение получает префикс на
 * каждую свою строку — решение `OQ-2` для списка; заголовки применяются к
 * строке начала выделения
 */
data class LinePrefix(val prefix: String, val eachSelectedLine: Boolean = false) : InsertConstruct

/**
 * Заготовка макро-формы `цель[атрибут]` с русскими заместителями — решения
 * `OQ-5`: ссылка `https://адрес[текст]` без `link:`, картинка — блочная
 * `image::путь[]`.
 *
 * Заместители *выделяются* при вставке, чтобы печать заменяла их сразу:
 * пустое выделение выделяет цель, обёртка выделения ставит выделенный текст
 * на место цели (`⌶` таблицы заготовок) и выделяет заместитель атрибута.
 *
 * @property prefix неизменяемая голова формы: `"https://"`, `"image::"`
 * @property targetPlaceholder русский заместитель цели: `"адрес"`, `"путь"`
 * @property attributePlaceholder заместитель в квадратных скобках; пустая
 * строка — каретка встаёт между скобками
 * @property block блочная форма: с начала строки, в середине непустой строки
 * отделяется переводами строк (правило блочных заготовок аналитики)
 */
data class MacroTemplate(
    val prefix: String,
    val targetPlaceholder: String,
    val attributePlaceholder: String = "",
    val block: Boolean = false,
) : InsertConstruct

/**
 * Блочная заготовка с одним слотом — конструкции раскрытия `›` (`FR-11`):
 * таблица, admonition, блок кода. Формы — таблица «Заготовки конструкций»
 * аналитики; admonition — абзацная `NOTE: текст` (дорешённый `OQ-5`).
 *
 * Слот (`⌶` таблицы заготовок) стоит между [before] и [after]. Пустое
 * выделение вставляет [placeholder] и выделяет его (печать заменяет сразу);
 * пустой заместитель — просто каретка в слоте. Непустое выделение встаёт в
 * слот, каретка — за вставленным текстом.
 *
 * Всегда с начала строки: в середине непустой строки заготовка отделяется
 * переводами строк с обеих сторон — правило блочных заготовок аналитики,
 * то же, что у блочной `image::`.
 */
data class BlockTemplate(
    val before: String,
    val after: String,
    val placeholder: String = "",
) : InsertConstruct

/**
 * Конструкции базового ряда — формы из таблицы «Заготовки конструкций»
 * аналитики и решений владельца `OQ-2`/`OQ-5`.
 */
object InsertConstructs {
    /** `=` — заголовок документа. */
    val documentTitle = LinePrefix("= ")

    /** `==` — заголовок раздела. */
    val sectionTitle = LinePrefix("== ")

    /** `*B*` — полужирный. */
    val bold = InlineWrap("*")

    /** `_I_` — курсив. */
    val italic = InlineWrap("_")

    /** `` `c` `` — моноширинный. */
    val monospace = InlineWrap("`")

    /** Маркер списка; на многострочном выделении — на каждую строку (`OQ-2`). */
    val listItem = LinePrefix("* ", eachSelectedLine = true)

    /** `link` — макро-форма URL без `link:` (`OQ-5`). */
    val link = MacroTemplate(prefix = "https://", targetPlaceholder = "адрес", attributePlaceholder = "текст")

    /** `img` — блочная `image::` (`OQ-5`). */
    val image = MacroTemplate(prefix = "image::", targetPlaceholder = "путь", block = true)

    // Конструкции раскрытия `›` (FR-11, вид раскрытия — решение OQ-1).

    /** Таблица: минимальная рамка `|===` с одной ячейкой, каретка в ней. */
    val table = BlockTemplate(before = "|===\n| ", after = "\n|===")

    /** Admonition — абзацная `NOTE: текст` (дорешённый `OQ-5`). */
    val admonition = BlockTemplate(before = "NOTE: ", after = "", placeholder = "текст")

    /** Блок кода: `[source]` и пара `----`, каретка на пустой строке между ними. */
    val listing = BlockTemplate(before = "[source]\n----\n", after = "\n----")
}
