package io.github.olegnyr.adocmobile.git

/**
 * Секрет в пути от поля ввода до платформенного хранилища (`FR-26`, `FR-28`).
 *
 * Обычный класс с задушенным [toString] — не `data class` и не голая строка
 * намеренно: `data class` печатает поля в `toString`, и секрет утёк бы в лог
 * первым же `println(request)` или сообщением упавшего теста (`NFR-8`,
 * `TC-31`). Значение достаётся только явным обращением к [value].
 *
 * Сравнение по значению не реализовано сознательно: секреты не сравнивают,
 * их предъявляют.
 */
class Secret(val value: String) {

    override fun toString(): String = MASK

    private companion object {
        const val MASK = "•••"
    }
}

/**
 * Способ авторизации операции (`FR-3`, `FR-26`): передаётся вместе с
 * запросом и не хранится в моделях экранов дольше необходимого.
 * SSH-ключ приходит этапом E4 (решение OQ-3).
 */
sealed interface GitAuth {

    /** Анонимный доступ — публичный репозиторий. */
    data object None : GitAuth

    /**
     * Персональный токен: предъявляется как имя пользователя с пустым
     * паролем (механика из разведки, Q2). Не `data class` — по правилу
     * [Secret]: печататься нечему.
     */
    class Token(val token: Secret) : GitAuth
}
