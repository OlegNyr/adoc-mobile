package io.github.olegnyr.adocmobile.document

/**
 * Тип переводов строк в файле.
 *
 * Заведён отдельным типом, а не флагом «был ли CRLF», по требованию `FR-4`:
 * тип определяется при чтении и хранится в модели, потому что вывести его из
 * текста при записи нельзя — пользователь мог удалить все переводы строк.
 *
 * Внутри редактора текст всегда нормализован к `\n`: иначе позиции кареток и
 * диапазоны подсветки пришлось бы считать по-разному для CRLF и LF, и каждая
 * работа с текстом получила бы скрытое двухсимвольное исключение.
 */
enum class LineEnding(val chars: String) {
    /** Unix, macOS, Git по умолчанию. */
    Lf("\n"),

    /** Windows. */
    Crlf("\r\n"),

    /** Классический macOS до версии 10. Редок, но переписать его в LF значит поменять каждую строку файла. */
    Cr("\r"),
    ;

    companion object {
        /**
         * Тип переводов строк по содержимому файла.
         *
         * Берётся *первый встреченный*: смешанные файлы не редкость после
         * правки разными инструментами, и любое правило здесь произвольно —
         * но это самое предсказуемое.
         *
         * Файл без единого перевода строки даёт [Lf]: гадать не о чем, а LF
         * не мешает Git и не удивляет.
         */
        fun detect(fileText: String): LineEnding {
            val carriageReturn = fileText.indexOf('\r')
            val lineFeed = fileText.indexOf('\n')

            return when {
                carriageReturn == -1 -> Lf
                lineFeed == carriageReturn + 1 -> Crlf
                lineFeed == -1 || carriageReturn < lineFeed -> Cr
                else -> Lf
            }
        }
    }
}

/**
 * Текст файла — в текст редактора: любые переводы строк приводятся к `\n`.
 *
 * Порядок замен важен: сначала CRLF целиком, иначе одиночная замена `\r`
 * оставила бы после себя лишний пустой перевод строки.
 */
fun String.toEditorText(): String = replace("\r\n", "\n").replace('\r', '\n')

/**
 * Текст редактора — в текст файла: `\n` разворачивается в сохранённый тип.
 *
 * На вход намеренно принимается уже нормализованный текст. Если в нём почему-то
 * остались `\r`, они сначала нормализуются — иначе наивная замена `\n` на
 * `\r\n` превратила бы уцелевший `\r\n` в `\r\r\n`.
 */
fun String.toFileText(lineEnding: LineEnding): String {
    if (lineEnding == LineEnding.Lf) return toEditorText()
    return toEditorText().replace("\n", lineEnding.chars)
}
