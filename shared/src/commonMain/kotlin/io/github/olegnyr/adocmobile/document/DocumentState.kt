package io.github.olegnyr.adocmobile.document

/**
 * Откуда пришёл документ.
 *
 * Намеренно не тип платформы: `FR-9` требует, чтобы модель документа жила в
 * общем коде и не тянула за собой `Uri`, `NSURL` или что там окажется дальше.
 * Платформенная сторона хранит свою ссылку и сопоставляет её с [id].
 *
 * @property id непрозрачный идентификатор источника, понятный платформенному шву
 * @property displayName имя для показа пользователю, обычно имя файла
 */
data class DocumentSource(
    val id: String,
    val displayName: String,
)

/**
 * Открытый документ: текст, источник, тип переводов строк и состояние записи.
 *
 * Тип неизменяемый, а операции возвращают новое состояние. Так признак
 * несохранённых изменений невозможно рассогласовать с текстом: он не хранится
 * отдельным флагом, а вычисляется сравнением (`FR-8`).
 *
 * @property text текст в виде, нормализованном к `\n` — см. [LineEnding]
 * @property savedText текст, который в последний раз успешно оказался в файле
 * @property savedAt время последней успешной записи в миллисекундах эпохи Unix;
 * `null` — записи не было. Единица зафиксирована здесь, потому что заполнять
 * поле будет платформенный шов, и договориться нужно до его появления.
 * @property lastSaveFailed последняя попытка записи закончилась отказом.
 * Нужно `FR-19`: после отказа автосохранение приостанавливается до следующей
 * явной правки, иначе приложение будет биться о закрытый файл каждую паузу.
 */
data class DocumentState(
    val source: DocumentSource,
    val text: String,
    val lineEnding: LineEnding,
    val savedText: String,
    val savedAt: Long? = null,
    val lastSaveFailed: Boolean = false,
) {
    /**
     * Есть ли расхождение с тем, что записано на диск.
     *
     * Сравнение, а не флаг: правка и отмена этой правки возвращают документ в
     * сохранённое состояние, и метка «не сохранён» обязана погаснуть.
     * Флаг, поднятый по событию ввода, так не умеет — он горел бы после любого
     * нажатия клавиши, даже когда текст вернулся к исходному.
     */
    val isModified: Boolean get() = text != savedText

    /** Текст в том виде, в каком он должен лечь в файл: с исходными переводами строк. */
    fun fileText(): String = text.toFileText(lineEnding)

    /**
     * Пользователь изменил текст.
     *
     * Текст нормализуется здесь, а не доверяется вызывающему: иначе вставка из
     * буфера обмена с CRLF (текст из другого приложения или из веба) положила бы
     * в модель ненормализованную строку, и `isModified` начал бы врать — метка
     * «не сохранён» загоралась бы при полном совпадении с диском и не гасла
     * после возврата текста. Инвариант, который держится на соглашении
     * вызывающего, ломается ровно тогда, когда появляется второй вызывающий.
     */
    fun edited(newText: String): DocumentState =
        copy(text = newText.toEditorText(), lastSaveFailed = false)

    /** Запись удалась: текущий текст стал сохранённым. */
    fun saved(at: Long): DocumentState =
        copy(savedText = text, savedAt = at, lastSaveFailed = false)

    /**
     * Запись не удалась.
     *
     * Текст никуда не девается, признак изменений продолжает гореть, отметка
     * времени не сдвигается (`FR-17`) — но факт отказа запоминается, иначе
     * автосохранение будет повторять неудачную попытку каждую паузу ввода.
     * Снимается следующей правкой или успешной записью.
     */
    fun saveFailed(): DocumentState = copy(lastSaveFailed = true)

    companion object {
        /**
         * Документ, только что прочитанный из источника.
         *
         * @param fileText содержимое файла как есть, с его переводами строк
         */
        fun opened(source: DocumentSource, fileText: String): DocumentState {
            val text = fileText.toEditorText()
            return DocumentState(
                source = source,
                text = text,
                lineEnding = LineEnding.detect(fileText),
                savedText = text,
                savedAt = null,
            )
        }
    }
}
