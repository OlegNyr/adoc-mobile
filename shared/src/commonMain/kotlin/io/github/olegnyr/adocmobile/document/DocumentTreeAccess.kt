package io.github.olegnyr.adocmobile.document

/**
 * Tree-доступ — слайс `SL-7`, решение владельца от 2026-08-17.
 *
 * Сценарий открытия меняется: пользователь выбирает *папку*, затем файл в ней.
 * Право покрывает дерево целиком, поэтому работают картинки рядом с документом
 * (`TC-34` фичи 003) и будущий `include`. Прежнее правило «ровно одно право»
 * сохраняется — теперь это право на дерево, а не на одиночный файл.
 *
 * Общая половина шва: перечень записей каталога, фильтр документов, проход по
 * относительному пути. Платформе остаётся достать перечень детей и байты —
 * `NFR` «доля общего кода» выполняется составом файлов, как в [openDocument].
 */

/**
 * Ссылка на удерживаемое дерево — папку, выбранную пользователем.
 *
 * Не тип платформы по той же причине, что [DocumentSource] (`FR-9`):
 * платформенная сторона хранит свою ссылку и сопоставляет её с [id].
 *
 * @property id непрозрачный идентификатор дерева, понятный платформенному шву
 * @property displayName имя папки для показа пользователю
 */
data class TreeSource(
    val id: String,
    val displayName: String,
)

/**
 * Почему папка не открылась или не перечислилась.
 *
 * Отдельное перечисление, а не переиспользование [DocumentAccessError], по
 * прецеденту [DocumentWriteError]: у файла есть исход «не UTF-8», которого не
 * бывает у папки, а сообщения обязаны говорить о папке, а не о файле — иначе
 * пользователь будет искать несуществующий файл.
 */
enum class TreeAccessError {
    /** Постоянное разрешение на дерево больше не действует — отозвано или потеряно системой. */
    PermissionLost,

    /** Папка исчезла: удалена, накопитель отключён, облачный провайдер разлогинен. */
    NotFound,

    /** Всё остальное: ошибка ввода-вывода, отказ провайдера. */
    ListFailed,
    ;

    /**
     * Сообщение пользователю — по правилу [DocumentAccessError.userMessage]:
     * текст — часть требования `FR-3` (потеря доступа — штатный сценарий с
     * понятным сообщением), а не оформление экрана.
     */
    fun userMessage(displayName: String): String = when (this) {
        PermissionLost ->
            "Доступ к папке «$displayName» больше не действует. Выберите её заново."

        NotFound ->
            "Папка «$displayName» не найдена: возможно, она удалена или перемещена."

        ListFailed ->
            "Не удалось прочитать содержимое папки «$displayName». Попробуйте открыть её ещё раз."
    }
}

/** Чем закончилось перечисление документов папки. */
sealed interface TreeListResult {

    /** Документы папки, отфильтрованные и упорядоченные, — возможно, ни одного. */
    data class Listed(val documents: List<DocumentSource>) : TreeListResult

    /** Перечислить не удалось; [error] уже содержит текст для пользователя. */
    data class Failed(val tree: TreeSource, val error: TreeAccessError) : TreeListResult
}

/**
 * Запись каталога, как её видит общая половина шва.
 *
 * @property id непрозрачный идентификатор записи, понятный платформенному шву;
 * совпадать с именем не обязан
 * @property name отображаемое имя записи — по нему идёт и фильтр документов,
 * и сопоставление сегментов относительного пути
 * @property isDirectory каталог, а не файл
 */
data class TreeEntry(
    val id: String,
    val name: String,
    val isDirectory: Boolean,
)

/**
 * Документы среди записей каталога: файлы `.adoc`, упорядоченные по имени.
 *
 * Правила закрыты тестами:
 *
 * * каталог документом не считается, даже если назван `notes.adoc`;
 * * расширение сверяется без учёта регистра — файл с Windows или из чужого
 *   архива остаётся документом;
 * * имя из одного расширения (`.adoc`) — скрытый файл, а не документ без имени;
 * * порядок — по имени без учёта регистра: провайдер порядка не обещает, а
 *   пользователь ищет файл глазами.
 *
 * Только `.adoc`: слайс перечисляет документы, а не файлы вообще, и расширять
 * перечень (`.asciidoc`, `.txt`) — решение владельца, а не умолчание фильтра.
 */
fun adocDocumentsOf(entries: List<TreeEntry>): List<TreeEntry> =
    entries
        .filter { entry ->
            !entry.isDirectory &&
                entry.name.length > ADOC_SUFFIX.length &&
                entry.name.endsWith(ADOC_SUFFIX, ignoreCase = true)
        }
        .sortedBy { it.name.lowercase() }

private const val ADOC_SUFFIX = ".adoc"

/**
 * Перечень детей каталога по его идентификатору; `null` — перечислить нельзя:
 * право отозвано, каталог исчез, провайдер отказал.
 *
 * Контракт платформенной стороны для [resolveTreePath]. Блокирующий, не
 * `suspend`, намеренно: единственный вызывающий — чтение картинки для перехвата
 * WebView, а перехват синхронный (см. `PreviewImageSource`).
 */
fun interface TreeChildren {
    fun childrenOf(directoryId: String): List<TreeEntry>?
}

/**
 * Идентификатор файла по относительному пути от корня дерева; `null` — файла
 * нет или путь недопустим.
 *
 * Второй рубеж после резолвера превью (`resolvePreviewImageRequest`): путь
 * приходит уже провалидированным, но выход за дерево обязан быть невозможен и
 * при ошибке резолвера — поэтому сегменты проверяются здесь заново, независимым
 * кодом, а не общей функцией с первым рубежом.
 *
 * Выйти из дерева нечем по построению: путь ни разу не склеивается со строкой
 * корня. Каждый сегмент сопоставляется с *именами реальных детей* текущего
 * каталога — у каталога нет ребёнка по имени `..`, а сегмент с разделителем не
 * переживает проверку. Ошибка перечисления на любом шаге — отказ, не догадка.
 */
fun resolveTreePath(rootId: String, relativePath: String, children: TreeChildren): String? {
    val segments = relativePath.split('/')
    if (segments.any { !isSafeTreeSegment(it) }) return null

    var directoryId = rootId
    for (directoryName in segments.dropLast(1)) {
        val entries = children.childrenOf(directoryId) ?: return null
        directoryId = entries
            .firstOrNull { it.isDirectory && it.name == directoryName }
            ?.id
            ?: return null
    }

    val entries = children.childrenOf(directoryId) ?: return null
    return entries.firstOrNull { !it.isDirectory && it.name == segments.last() }?.id
}

/**
 * Сегмент, которому можно доверять: не пустой, не `.`/`..`, без разделителей,
 * управляющих символов и `DEL`.
 *
 * Дублирует смысл проверки резолвера превью сознательно: рубежи обязаны падать
 * независимо, а общая функция превратила бы два рубежа в один с двумя вызовами.
 */
private fun isSafeTreeSegment(segment: String): Boolean =
    segment.isNotEmpty() &&
        segment != "." &&
        segment != ".." &&
        segment.none { it == '/' || it == '\\' || it.code < 0x20 || it.code == 0x7F }

/**
 * Файловый шов поверх дерева: то же чтение и запись, что у [DocumentFileAccess],
 * плюс перечень документов папки.
 *
 * Наследование от [DocumentFileAccess] намеренное: экран, построенный на
 * существующем контракте (открыть источник, записать, удержанный источник),
 * продолжает работать без правок — меняется только то, *откуда* берётся
 * источник: из перечня документов дерева, а не из диалога выбора файла.
 * [heldSource] означает последний открытый документ дерева — им экран
 * восстанавливает документ после перезапуска, как и раньше.
 *
 * [release] отдаёт право на *дерево*: правило «ровно одно право» действует на
 * уровне приложения, и право на дерево — это оно.
 */
interface DocumentTreeAccess : DocumentFileAccess {

    /**
     * Дерево, доступ к которому удерживается постоянным разрешением.
     *
     * `null` — удерживать нечего. Ненулевой ответ *не* обещает, что перечень
     * прочитается: право могло быть отозвано, папка удалена, и узнать об этом
     * можно только попыткой — [listDocuments] назовёт исход.
     */
    fun heldTree(): TreeSource?

    /**
     * Документы удерживаемого дерева: файлы `.adoc` его корня, по имени.
     *
     * Перечисляется корень, не поддеревья: сценарий слайса — «выбрать папку,
     * затем файл в ней». Пустой перечень — не отказ: папка без документов
     * показывается пустой, с правом создать файл в будущих слайсах.
     */
    suspend fun listDocuments(): TreeListResult
}
