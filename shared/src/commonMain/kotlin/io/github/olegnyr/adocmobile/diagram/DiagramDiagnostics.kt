package io.github.olegnyr.adocmobile.diagram

/**
 * Исход загрузки одной диаграммы — то, что можно записать в диагностику
 * (`NFR-8`, `TC-29`).
 *
 * Пользователю мы показываем одно и то же на любой отказ (`ADR-011`), и это
 * решение стоит цены: без диагностики таймаут неотличим от `404` и от чужих
 * байтов, а значит, продукт неотлаживаем в поле. Эта запись — единственный
 * канал, по которому исходы различаются.
 *
 * Чего в записи нет и не будет: *адреса* и *текста диаграммы*. Адрес обратим —
 * это содержимое документа пользователя, и попадать в журнал оно не имеет права
 * никогда. Длина адреса остаётся: по ней видно «диаграмма была большая», и она
 * ничего не раскрывает.
 */
data class DiagramLoadRecord(
    val outcome: DiagramLoadOutcome,
    val addressLength: Int,
    val elapsedMillis: Long,
) {
    /** Строка для журнала. Собирается здесь, чтобы её нельзя было собрать иначе. */
    override fun toString(): String =
        "диаграмма: ${outcome.name.lowercase()}, адрес $addressLength симв., $elapsedMillis мс"
}

/** Чем кончилась загрузка. */
enum class DiagramLoadOutcome {

    /** Изображение получено и принято. */
    Loaded,

    /** Транспорт не принёс байтов: нет сети, ошибка сервера, отказ. */
    Failed,

    /** Срок вышел раньше ответа. */
    TimedOut,

    /** Байты пришли, но это не изображение заявленного формата. */
    NotAnImage,

    /** Транспорт бросил исключение — своё, не отмену. */
    Broken,
}

/**
 * Куда уходит запись об исходе загрузки.
 *
 * Умолчание — никуда: настоящего журнала в проекте пока нет вовсе, он придёт
 * потоком диагностики (`T-090`). Шов заведён сейчас, потому что его форма — это
 * требование безопасности, а не удобство: собрать запись можно только через
 * [DiagramLoadRecord], и другого способа сказать что-либо об исходе нет.
 */
fun interface DiagramLoadLog {

    fun record(record: DiagramLoadRecord)

    companion object {

        /** Ничего не пишет. */
        val None: DiagramLoadLog = DiagramLoadLog { }
    }
}
