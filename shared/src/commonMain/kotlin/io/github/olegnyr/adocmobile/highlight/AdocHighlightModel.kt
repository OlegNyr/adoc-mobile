package io.github.olegnyr.adocmobile.highlight

/**
 * Модель результата подсветки: диапазоны и роли, без единого типа платформы.
 *
 * `FR-25` требует, чтобы выход сканера был платформенно-нейтральным, и это не
 * стилистическое пожелание. Список `(range, style)` — та самая точка, в которой
 * поле ввода можно заменить на платформенное, не трогая сканер; замеры `T-010`
 * показали, что такая замена вполне может понадобиться. Как только сюда попадёт
 * `SpanStyle` или `TextRange` из Compose, запасной путь закрыт.
 *
 * Поэтому здесь только `Int`, `String` и перечисления. Отображение роли в цвет
 * и начертание живёт выше, в `OutputTransformation`, и сканеру не видно.
 */

/**
 * Полуинтервал в *исходном* тексте: `start` включительно, `endExclusive` нет.
 *
 * Считается по исходнику, а не по тому, что увидит читатель превью: в редакторе
 * присутствуют и ограничители блоков, и экранирующие слэши, которых в выводе
 * Asciidoctor нет (`FR-20`, `FR-24`).
 */
data class AdocRange(val start: Int, val endExclusive: Int) {
    init {
        require(start >= 0) { "начало диапазона отрицательное: $start" }
        require(endExclusive >= start) { "конец диапазона раньше начала: $start..$endExclusive" }
    }

    val length: Int get() = endExclusive - start
}

/**
 * Роль подсветки — смысл фрагмента, а не его вид.
 *
 * Набор растёт по слайсам: `SL-1` завёл роли блочного автомата, `SL-2` — роли
 * строчных конструкций, `SL-3` — инлайн-роли. Роль, которой не соответствует
 * ни один тест-кейс закрытого слайса, здесь не заводится: макросы и ссылки
 * придут в `SL-4`.
 */
enum class AdocStyle {
    /** Строка-ограничитель блока: `----`, `====`, `////`, `|===` и прочие из `FR-2`. */
    BlockDelimiter,

    /**
     * Содержимое дословного блока (`listing`, `literal`, `passthrough`), а также
     * литеральный абзац по отступу из `FR-16` — он и есть литеральный блок без
     * ограничителя. Внутри разбора нет вовсе — `FR-3`.
     */
    VerbatimContent,

    /** Содержимое блока комментария `////` и строчный комментарий `//` из `FR-13`. */
    Comment,

    /**
     * Callout `<1>` — одно из двух исключений `FR-3`, которые видны даже внутри
     * дословного блока.
     */
    Callout,

    /**
     * Директива препроцессора: `include::` (второе исключение `FR-3` — препроцессор
     * отрабатывает до разбора структуры и потому пробивает дословное состояние),
     * а также условные `ifdef::`, `ifndef::`, `ifeval::`, `endif::` из `FR-14`.
     */
    PreprocessorDirective,

    // Заголовки `FR-7`. Уровень — часть роли, а не отдельное поле: `FR-25` держит
    // выход сканера списком пар «диапазон, роль», и приписать паре число значило бы
    // поменять форму выхода ради одной конструкции. Уровней ровно шесть — прогон
    // эталона 2026-08-17 показал, что семь знаков заголовком уже не являются.
    Heading0,
    Heading1,
    Heading2,
    Heading3,
    Heading4,
    Heading5,

    /**
     * Запись атрибута документа `:name: value` целиком, включая строки-продолжения
     * после `\` на конце (`FR-8`, `FR-9`).
     */
    AttributeEntry,

    /**
     * Маркер списка: `*`, `-`, `.`, `..` у маркированных и нумерованных, разделитель
     * `::`, `:::`, `::::`, `;;` у списка определений (`FR-10`).
     * Размечается только маркер: текст пункта остаётся под инлайн-разбор `SL-3`.
     */
    ListMarker,

    /** Термин списка определений — часть слева от разделителя (`FR-10`). */
    ListTerm,

    /** Заголовок блока `.Title` — без пробела после точки (`FR-11`). */
    BlockTitle,

    /** Список атрибутов блока `[style,attrs]` (`FR-11`). */
    BlockAttributes,

    /** Якорь блока в обеих формах — `[[id]]` и `[#id]` (`FR-11`). */
    Anchor,

    /** Метка абзацного admonition вместе с двоеточием: `WARNING:` (`FR-12`). */
    Admonition,

    /** Тематический разрыв: `'''`, а также ровно три `-`, `*` или `_` (`FR-15`). */
    ThematicBreak,

    /** Разрыв страницы `<<<` (`FR-15`). */
    PageBreak,

    // Инлайн-роли слайса `SL-3` (`FR-17`…`FR-20`). Диапазон покрывает конструкцию
    // целиком, вместе со знаками форматирования, и может пересекать перевод
    // строки: единица инлайн-разбора — логическая строка блока, а не строка
    // исходника (`FR-17`).

    /** Инлайновый passthrough: `+…+`, `++…++`, `+++…+++`, `pass:[…]` (`FR-18`). */
    InlinePassthrough,

    /** Полужирный: constrained `*…*` и unconstrained `**…**` (`FR-19`). */
    Bold,

    /** Курсив: `_…_` и `__…__` (`FR-19`). */
    Italic,

    /** Моноширинный текст в обратных апострофах, одиночных и сдвоенных (`FR-19`). */
    Monospace,

    /** Выделение: `#…#` и `##…##` (`FR-19`). */
    Highlight,

    /** Надстрочный `^…^` — только непрерывный текст без пробелов (`FR-19`). */
    Superscript,

    /** Подстрочный `~…~` — только непрерывный текст без пробелов (`FR-19`). */
    Subscript,
}

/** Пара «диапазон, роль» — единица выхода сканера по `FR-25`. */
data class AdocSpan(val range: AdocRange, val style: AdocStyle)

/** Тип блока по таблице ограничителей `FR-2`. */
enum class AdocBlockKind {
    Comment,
    Example,
    Listing,
    Literal,
    Open,
    Sidebar,
    Quote,
    Passthrough,
    Table,
}

/**
 * Кадр стека блоков — пара «тип, длина ограничителя» из `FR-1`.
 *
 * Длина хранится, потому что закрывающий ограничитель засчитывается только при
 * совпадении и символа, и длины: `-----` не закрывает блок, открытый `----`.
 * Длина считается по всей строке ограничителя, включая ведущий `|` у таблицы,
 * — так правило совпадения одно на все девять типов.
 *
 * Типов в кадре два, и разводить их пришлось из-за маскарада (`FR-5`): метка
 * `[listing]` над `....` меняет *тип блока*, но не меняет знаки, которыми он
 * закрывается. Если бы кадр хранил один тип, закрывающая строка `....` перестала
 * бы совпадать с кадром `listing`, и блок не закрылся бы никогда.
 *
 * @property kind эффективный тип блока — по нему решается, разбирается ли
 * содержимое и пускает ли блок внутрь вложенные блоки.
 * @property delimiterKind тип, заданный самими знаками ограничителя; по нему и по
 * длине опознаётся закрывающая строка. Без маскарада совпадает с [kind].
 */
data class AdocBlockFrame(
    val kind: AdocBlockKind,
    val delimiterLength: Int,
    val delimiterKind: AdocBlockKind = kind,
)

/**
 * Результат прохода сканера.
 *
 * @property spans диапазоны с ролями, отсортированные по началу; при совпадении
 * начал первым идёт более широкий диапазон, чтобы вложенная роль ложилась поверх
 * объемлющей.
 * @property blockStates стек блоков *после* каждой строки исходника, по одному
 * элементу на строку. Это внутреннее состояние автомата, вынесенное наружу
 * намеренно: на нём проверяется вложенность (`TC-3`, `TC-4`) и на него обопрётся
 * инкрементальный проход `FR-27` — ему нужно знать, где состояние совпало с
 * прежним.
 */
data class AdocScan(
    val spans: List<AdocSpan>,
    val blockStates: List<List<AdocBlockFrame>>,
)
