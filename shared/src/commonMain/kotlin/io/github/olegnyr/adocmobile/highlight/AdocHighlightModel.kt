package io.github.olegnyr.adocmobile.highlight

/**
 * Модель результата подсветки: диапазоны и роли, без единого типа платформы.
 *
 * `FR-25` требует, чтобы выход сканера был платформенно-нейтральным, и это не
 * стилистическое пожелание. Список `(range, style)` — та самая точка, в которой
 * поле ввода можно заменить на платформенное, не трогая сканер; замеры `T-010`
 * показали, что такая замена вполне может понадобиться. Как только сюда попадёт
 * `SpanStyle` или `TextRange` из Compose, запасной путь закрыт.
 *
 * Поэтому здесь только `Int`, `String` и перечисления. Отображение роли в цвет
 * и начертание живёт выше, в `OutputTransformation`, и сканеру не видно.
 */

/**
 * Полуинтервал в *исходном* тексте: `start` включительно, `endExclusive` нет.
 *
 * Считается по исходнику, а не по тому, что увидит читатель превью: в редакторе
 * присутствуют и ограничители блоков, и экранирующие слэши, которых в выводе
 * Asciidoctor нет (`FR-20`, `FR-24`).
 */
data class AdocRange(val start: Int, val endExclusive: Int) {
    init {
        require(start >= 0) { "начало диапазона отрицательное: $start" }
        require(endExclusive >= start) { "конец диапазона раньше начала: $start..$endExclusive" }
    }

    val length: Int get() = endExclusive - start
}

/**
 * Роль подсветки — смысл фрагмента, а не его вид.
 *
 * Набор намеренно беден: слайс `SL-1` закрывает только блочный автомат, и роль,
 * которой не соответствует ни один тест-кейс слайса, здесь не заводится.
 * Строчные конструкции и инлайн-разметка добавят свои роли в `SL-2`…`SL-4`.
 */
enum class AdocStyle {
    /** Строка-ограничитель блока: `----`, `====`, `////`, `|===` и прочие из `FR-2`. */
    BlockDelimiter,

    /**
     * Содержимое дословного блока (`listing`, `literal`, `passthrough`).
     * Внутри него разбора нет вовсе — `FR-3`.
     */
    VerbatimContent,

    /** Содержимое блока комментария `////`. */
    Comment,

    /**
     * Callout `<1>` — одно из двух исключений `FR-3`, которые видны даже внутри
     * дословного блока.
     */
    Callout,

    /**
     * Директива препроцессора `include::`. Второе исключение `FR-3`: препроцессор
     * отрабатывает до разбора структуры и потому пробивает дословное состояние.
     */
    PreprocessorDirective,
}

/** Пара «диапазон, роль» — единица выхода сканера по `FR-25`. */
data class AdocSpan(val range: AdocRange, val style: AdocStyle)

/** Тип блока по таблице ограничителей `FR-2`. */
enum class AdocBlockKind {
    Comment,
    Example,
    Listing,
    Literal,
    Open,
    Sidebar,
    Quote,
    Passthrough,
    Table,
}

/**
 * Кадр стека блоков — пара «тип, длина ограничителя» из `FR-1`.
 *
 * Длина хранится, потому что закрывающий ограничитель засчитывается только при
 * совпадении и символа, и длины: `-----` не закрывает блок, открытый `----`.
 * Длина считается по всей строке ограничителя, включая ведущий `|` у таблицы,
 * — так правило совпадения одно на все девять типов.
 */
data class AdocBlockFrame(val kind: AdocBlockKind, val delimiterLength: Int)

/**
 * Результат прохода сканера.
 *
 * @property spans диапазоны с ролями, отсортированные по началу; при совпадении
 * начал первым идёт более широкий диапазон, чтобы вложенная роль ложилась поверх
 * объемлющей.
 * @property blockStates стек блоков *после* каждой строки исходника, по одному
 * элементу на строку. Это внутреннее состояние автомата, вынесенное наружу
 * намеренно: на нём проверяется вложенность (`TC-3`, `TC-4`) и на него обопрётся
 * инкрементальный проход `FR-27` — ему нужно знать, где состояние совпало с
 * прежним.
 */
data class AdocScan(
    val spans: List<AdocSpan>,
    val blockStates: List<List<AdocBlockFrame>>,
)
